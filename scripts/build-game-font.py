"""Generate disjoint WOFF2 subsets while preserving the source font's coverage."""

import hashlib
import json
from collections import defaultdict
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "cmdysj.ttf"
OUTPUT = ROOT / "src/assets/fonts"
CSS = ROOT / "src/styles/game-font.css"


def unicode_ranges(points):
    ranges = []
    start = end = None
    for point in sorted(points):
        if end is not None and point == end + 1:
            end = point
            continue
        if start is not None:
            ranges.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
        start = end = point
    if start is not None:
        ranges.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
    return ",".join(ranges)


def main():
    with TTFont(SOURCE) as original:
        coverage = set(original.getBestCmap())
    ui_points = set()
    for directory in [ROOT / "src", ROOT / "shared"]:
        for path in sorted(directory.rglob("*")):
            if path.suffix not in {".ts", ".tsx"} or ".generated." in path.name:
                continue
            ui_points.update(map(ord, path.read_text(encoding="utf-8")))

    # Latin, punctuation and all existing UI text load before less common glyphs.
    latin = {point for point in coverage if point < 0x300 or 0x2000 <= point <= 0x206F
             or 0x3000 <= point <= 0x303F or 0xFF00 <= point <= 0xFFEF}
    common = (coverage & ui_points) - latin
    buckets = defaultdict(set)
    for point in coverage - latin - common:
        buckets[(point // 256) * 256].add(point)
    groups = [("latin", latin), ("ui", common)] + [
        (f"range-{start:04x}", points) for start, points in sorted(buckets.items())
    ]

    OUTPUT.mkdir(parents=True, exist_ok=True)
    CSS.parent.mkdir(parents=True, exist_ok=True)
    entries = []
    blocks = ["/* Generated by scripts/build-game-font.py. Do not edit by hand. */"]
    retained = set()
    for name, points in groups:
        if not points:
            continue
        font = TTFont(SOURCE, recalcTimestamp=False)
        options = subset.Options()
        options.flavor = "woff2"
        options.recalc_timestamp = False
        options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=points)
        subsetter.subset(font)
        font.flavor = "woff2"
        output = OUTPUT / f"game-{name}.woff2"
        font.save(output)
        font.close()
        with TTFont(output) as check:
            actual = set(check.getBestCmap())
        if actual != points or retained & actual:
            raise RuntimeError(f"Font coverage mismatch: {name}")
        retained.update(actual)
        entries.append({"file": output.name, "bytes": output.stat().st_size,
                        "codepoints": len(points), "unicodeRange": unicode_ranges(points)})
        blocks.append("\n".join([
            "@font-face {",
            "  font-family: 'Tower Defence';",
            f"  src: url('../assets/fonts/{output.name}') format('woff2');",
            "  font-weight: 400;",
            "  font-style: normal;",
            "  font-display: swap;",
            f"  unicode-range: {unicode_ranges(points)};",
            "}",
        ]))
        print(f"{name}: {len(points)} codepoints, {output.stat().st_size:,} bytes", flush=True)

    if retained != coverage:
        raise RuntimeError("The generated subsets do not preserve full font coverage")
    CSS.write_text("\n\n".join(blocks) + "\n", encoding="utf-8")
    manifest = {
        "source": "cmdysj.ttf", "sourceBytes": SOURCE.stat().st_size,
        "sourceSha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        "codepoints": len(coverage), "totalBytes": sum(entry["bytes"] for entry in entries),
        "subsets": entries,
    }
    (OUTPUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Verified {len(coverage):,} codepoints; total {manifest['totalBytes']:,} bytes.")


if __name__ == "__main__":
    main()
